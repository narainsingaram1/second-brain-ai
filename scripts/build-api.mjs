// Bundles each server/routes/*.ts into a self-contained api/<name>.js for Vercel Functions.
// The app's TypeScript uses bundler-style imports (no file extensions) that Node's ESM loader cannot
// resolve, so the functions ship pre-bundled. npm packages stay external and are traced by Vercel.
//
//   node scripts/build-api.mjs           write api/*.js
//   node scripts/build-api.mjs --check   exit 1 if api/*.js is out of date (used by the tests)
import { rolldown } from "rolldown";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const routesDir = path.join(root, "server/routes");
const outDir = path.join(root, "api");
const header = "// Generated by `npm run build:api` from server/routes. Do not edit; run the script after changing server code.\n";

export async function bundleRoutes() {
  const outputs = new Map();
  for (const file of (await readdir(routesDir)).filter(f => f.endsWith(".ts")).sort()) {
    const bundle = await rolldown({
      input: path.join(routesDir, file),
      platform: "node",
      // Bare specifiers (npm packages and node: builtins) are installed on Vercel; everything else is inlined.
      external: id => !id.startsWith(".") && !path.isAbsolute(id) && !id.startsWith("\0"),
      // Browser modules read Vite's import.meta.env; on the server those values are unused.
      transform: { define: { "import.meta.env": "{}" } },
      logLevel: "warn",
    });
    const { output } = await bundle.generate({ format: "esm", codeSplitting: false });
    await bundle.close();
    outputs.set(file.replace(/\.ts$/, ".js"), header + output[0].code);
  }
  return outputs;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = await bundleRoutes();
  if (process.argv.includes("--check")) {
    const stale = [];
    for (const [name, code] of outputs) {
      const current = await readFile(path.join(outDir, name), "utf8").catch(() => "");
      if (current !== code) stale.push(name);
    }
    if (stale.length) { console.error(`api/ is out of date (${stale.join(", ")}). Run npm run build:api.`); process.exit(1); }
  } else {
    await mkdir(outDir, { recursive: true });
    for (const [name, code] of outputs) await writeFile(path.join(outDir, name), code);
    console.log(`Wrote ${[...outputs.keys()].map(n => `api/${n}`).join(", ")}`);
  }
}
